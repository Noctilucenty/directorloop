import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source = await fs.readFile(new URL('../src/lib/transfer.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { transferEvidence, rankChange } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const fixture = async name => JSON.parse(await fs.readFile(new URL(`../src/api/fixtures/${name}`, import.meta.url), 'utf8'));
const [reports, policy] = await Promise.all([fixture('transfers.json'), fixture('policy.json')]);
const report = reports[0];
const evidence = transferEvidence(report, policy);
assert.equal(evidence[0].video_id, 'aptip');
assert.equal(evidence[0].mutation, 'PAYOFF_EARLIER');
assert.equal(evidence[0].outcome, 'loss');
assert.ok(evidence.every(e => e.policyVersion <= report.policy_version && e.video_id !== report.video_id));
assert.ok(evidence.every(e => e.experiment_id !== report.oracle_experiment));
assert.deepEqual(transferEvidence(report, null), []);
assert.deepEqual(transferEvidence({...report,policy_version:0},policy), []);
assert.deepEqual(rankChange('RESULT_FIRST',report.modes.none.order,report.modes.learned.order), {before:2,after:1,delta:1});
assert.deepEqual(rankChange('PAYOFF_EARLIER',report.modes.none.order,report.modes.learned.order), {before:1,after:3,delta:-2});
assert.deepEqual(rankChange('MISSING',[],[]), {before:null,after:null,delta:null});
assert.equal(report.modes.learned.first_outcome_on_b,'loss');
console.log('11 transfer evidence checks passed: historical cutoff, source identity, rank changes, empty evidence, and negative outcome.');
